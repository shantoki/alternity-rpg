/**
 * @file RobotData.js
 * @description TypeDataModel: Schema for the 'robot' Actor type.
 *
 * Source: `7Foundry.md` by Ivo Elezović — a fan supplement, used deliberately in
 * place of the official *Dataware*. Dataware's robot tables are the worst-damaged
 * material in the whole corpus: D17 (ability limits), D18 (hardware) and D19 (the
 * entire point-buy parts list) are unreadable in the scan. 7Foundry's equivalents
 * are intact, and it ships eight fully worked builds that serve as test fixtures —
 * the unit tests assert against its CIMDR-13 statblock line by line.
 *
 * What makes a robot different from every other actor in this system is that it is
 * built against **four simultaneous budgets**, and spending one usually costs you
 * another:
 *
 *   1. Chassis Points   CP = h x (30 - CON). Runs *inverse* to Constitution: a
 *                       tougher robot is more densely packed and has less room
 *                       inside it. Costs are paid in 10%/5%/1% denominations that
 *                       are each rounded separately, so the arithmetic does not
 *                       commute — six 5% systems cost more than one 30% system.
 *   2. Power Points     Generated by the supply, drawn by everything installed. A
 *                       build may legally run over; the robot then chooses what to
 *                       shut down, so this is a warning, not an error.
 *   3. Active memory    A robot's *skills are programs*. The OS holds one slot,
 *                       each broad skill one, each specialty skill one per rank.
 *                       A robot that cannot hold its whole kit swaps skills in and
 *                       out mid-scene, which costs actions.
 *   4. Skill Points     30 + (3 x INT), net of perks bought and flaws taken.
 *
 * Robots never have Last Resort points — a Free Agent robot takes an extra
 * resistance-modifier increase instead — and have no fatigue track unless built
 * with biological or synthetic-tissue actuators.
 *
 * Scope: this is a record sheet for a designed robot, in the same spirit as the
 * ship sheets. It validates every budget and derives every stat, but skills live
 * here as inline rows rather than going through AlternityCharacterState, so a
 * robot does not yet roll through the shared hero machinery.
 */

const { fields } = foundry.data;

import {
    AlternityMathService,
    ROBOT_SIZES,
    ROBOT_PROCESSORS,
    ROBOT_CABLING,
    ROBOT_LIMB_PERCENT,
} from '../services/alternity-math.js';

export { ROBOT_SIZES, ROBOT_PROCESSORS, ROBOT_CABLING };

/** The six abilities, in sheet order. */
export const ROBOT_ABILITIES = Object.freeze(['STR', 'DEX', 'CON', 'INT', 'WIL', 'PER']);

/**
 * Professions a robot may take. "A Mindwalker robot is not possible until PL9,
 * and even then only with a positronic brain."
 */
export const ROBOT_PROFESSIONS = Object.freeze([
    'None', 'Combat Spec', 'Free Agent', 'Tech Op', 'Diplomat', 'Mindwalker',
]);

/** System groups, following the chapter order of 7Foundry Ch.4. */
export const ROBOT_SYSTEM_CATEGORIES = Object.freeze([
    'Chassis', 'Power Supply', 'Processor', 'Actuators', 'Cabling', 'Sensors',
    'Data Ports', 'Limbs', 'Manipulators', 'Propulsion', 'Casing',
    'Weapon Support', 'Miscellaneous',
]);

/**
 * How a system's chassis cost is quoted. The book does both: percentages for
 * things that scale with the chassis (cabling, limbs, wheels) and flat points for
 * things that do not (processors, sensors).
 */
export const CHASSIS_COST_MODES = Object.freeze(['points', 'percent']);

function damageSchema() {
    return new fields.NumberField({ required: true, nullable: false, integer: true, initial: 0, min: 0 });
}

export class RobotData extends foundry.abstract.TypeDataModel {

    /** @override */
    static defineSchema() {
        return {
            // ── Identity ─────────────────────────────────────────────────────
            concept: new fields.StringField({ required: false, initial: '' }),
            shape:   new fields.StringField({ required: false, initial: '' }),

            size: new fields.StringField({
                required: true, nullable: false, initial: 'Medium',
                choices: Object.keys(ROBOT_SIZES),
            }),

            progressLevel: new fields.NumberField({
                required: true, nullable: false, integer: true, initial: 6, min: 5, max: 9,
            }),

            profession: new fields.StringField({
                required: true, nullable: false, initial: 'None', choices: ROBOT_PROFESSIONS,
            }),

            weight: new fields.NumberField({ required: true, nullable: false, integer: false, initial: 0, min: 0 }),
            cost:   new fields.StringField({ required: false, initial: '' }),

            // ── Obedience (7Foundry Ch.3.3) ──────────────────────────────────
            // A non-emancipated robot is property and starts with no money at all.
            isEmancipated:      new fields.BooleanField({ required: true, initial: false }),
            hasRestrainingBolt: new fields.BooleanField({ required: true, initial: false }),

            // ── Abilities ────────────────────────────────────────────────────
            abilities: new fields.SchemaField(Object.fromEntries(
                ROBOT_ABILITIES.map((key) => [key, new fields.NumberField({
                    required: true, nullable: false, integer: true, initial: 1, min: 1,
                })])
            )),

            // ── Hardware that constrains everything else ─────────────────────
            processor: new fields.StringField({
                required: true, nullable: false, initial: 'PL6-Ordinary',
                choices: Object.keys(ROBOT_PROCESSORS),
            }),

            cabling: new fields.StringField({
                required: true, nullable: false, initial: 'Parallel',
                choices: Object.keys(ROBOT_CABLING),
            }),

            // Biological and synthetic-tissue actuators are the stated exception to
            // "robots do not have a fatigue rating".
            hasFatigueTrack: new fields.BooleanField({ required: true, initial: false }),

            // An installed AI fills every memory slot the processor has, which also
            // disables every chipset that needs a slot as a communication buffer.
            hasInstalledAI: new fields.BooleanField({ required: true, initial: false }),

            // Slots held open by boost / accelerator / targeting chipsets and the
            // Grid coprocessor while they are switched on.
            reservedMemorySlots: new fields.NumberField({
                required: true, nullable: false, integer: true, initial: 0, min: 0,
            }),

            // ── Budgets ──────────────────────────────────────────────────────
            powerGenerated: new fields.NumberField({
                required: true, nullable: false, integer: false, initial: 0, min: 0,
            }),

            // Each limb costs 5% of the chassis and gives 5% back inside the limb —
            // net zero, but the rounding still bites, so it is counted properly.
            limbCount: new fields.NumberField({
                required: true, nullable: false, integer: true, initial: 0, min: 0,
            }),

            // ── Damage taken (maxima are derived from CON) ────────────────────
            damage: new fields.SchemaField({
                stun:    damageSchema(),
                wound:   damageSchema(),
                mortal:  damageSchema(),
                fatigue: damageSchema(),
            }),

            // ── Installed systems ────────────────────────────────────────────
            systems: new fields.ArrayField(new fields.SchemaField({
                name: new fields.StringField({ required: true, nullable: false, initial: '' }),
                category: new fields.StringField({
                    required: true, nullable: false, initial: 'Miscellaneous',
                    choices: ROBOT_SYSTEM_CATEGORIES,
                }),
                // A row is a *group* of identical systems, because the book prices
                // groups as a whole ("6 wheels ... 30%"), not one at a time.
                quantity: new fields.NumberField({ required: true, nullable: false, integer: true, initial: 1, min: 0 }),
                costMode: new fields.StringField({
                    required: true, nullable: false, initial: 'points', choices: CHASSIS_COST_MODES,
                }),
                chassisPoints:  new fields.NumberField({ required: true, nullable: false, integer: true, initial: 0, min: 0 }),
                chassisPercent: new fields.NumberField({ required: true, nullable: false, integer: true, initial: 0, min: 0 }),
                // Power draw can be fractional — the CIMDR-13's feet draw 8.5.
                powerPoints: new fields.NumberField({ required: true, nullable: false, integer: false, initial: 0 }),
                cost:      new fields.StringField({ required: false, initial: '' }),
                notes:     new fields.StringField({ required: false, initial: '' }),
                isOffline: new fields.BooleanField({ required: true, initial: false }),
            }), { initial: [] }),

            // ── Skills (programs, in memory terms) ───────────────────────────
            skills: new fields.ArrayField(new fields.SchemaField({
                name:    new fields.StringField({ required: true, nullable: false, initial: '' }),
                isBroad: new fields.BooleanField({ required: true, initial: false }),
                rank:    new fields.NumberField({ required: true, nullable: false, integer: true, initial: 0, min: 0 }),
                // Partial loads are legal: a robot may hold 5 of its 8 ranks.
                ranksLoaded: new fields.NumberField({ required: true, nullable: false, integer: true, initial: 0, min: 0 }),
                isLoaded:    new fields.BooleanField({ required: true, initial: true }),
                skillPointCost: new fields.NumberField({ required: true, nullable: false, integer: true, initial: 0, min: 0 }),
                ability: new fields.StringField({ required: false, initial: '' }),
            }), { initial: [] }),

            // ── Perks and flaws ──────────────────────────────────────────────
            perksFlaws: new fields.ArrayField(new fields.SchemaField({
                name: new fields.StringField({ required: true, nullable: false, initial: '' }),
                kind: new fields.StringField({
                    required: true, nullable: false, initial: 'Perk', choices: ['Perk', 'Flaw'],
                }),
                // Signed against the skill point pool: a perk spends, a flaw grants.
                skillPointChange: new fields.NumberField({ required: true, nullable: false, integer: true, initial: 0 }),
                notes: new fields.StringField({ required: false, initial: '' }),
            }), { initial: [] }),

            // ── Free text ────────────────────────────────────────────────────
            brawlingDamage: new fields.StringField({ required: false, initial: '' }),
            notes:       new fields.HTMLField({ required: false, initial: '' }),
            description: new fields.HTMLField({ required: false, initial: '' }),
        };
    }

    /** @override */
    prepareDerivedData() {
        const abilities = this.abilities ?? {};
        const con = abilities.CON ?? 1;
        const int = abilities.INT ?? 1;
        const dex = abilities.DEX ?? 1;

        const sizeInfo = ROBOT_SIZES[this.size] ?? ROBOT_SIZES.Medium;
        const processor = ROBOT_PROCESSORS[this.processor] ?? null;
        const cabling   = ROBOT_CABLING[this.cabling] ?? null;

        this.sizeInfo  = sizeInfo;
        this.processorInfo = processor;
        this.cablingInfo   = cabling;

        // ── Budget 1: Chassis Points ─────────────────────────────────────────
        const chassis = AlternityMathService.calculateChassisPoints(this.size, con);
        this.chassisPoints = chassis.chassisPoints;
        this.chassisFactors = chassis.factors;
        this.sizeFactor = chassis.sizeFactor;
        this.isConOutOfRange = chassis.isConOutOfRange;

        // Cost each system row, resolving percentage rows through the
        // minimum-factor rule rather than multiplying out.
        let chassisSpent = 0;
        let powerConsumed = 0;

        this.systemDetails = (this.systems ?? []).map((row, index) => {
            let points;
            let breakdown = null;
            let unitByUnitPoints = null;
            if (row.costMode === 'percent') {
                const totalPercent = (row.chassisPercent ?? 0) * (row.quantity ?? 1);
                breakdown = AlternityMathService.decomposeChassisPercent(totalPercent, chassis.factors);
                points = breakdown.chassisPoints;
                // What the group would have cost if each unit were paid for
                // separately. The book's six-wheel example turns on this being
                // different, so the sheet shows both numbers.
                unitByUnitPoints = (row.quantity ?? 1) * AlternityMathService
                    .decomposeChassisPercent(row.chassisPercent ?? 0, chassis.factors).chassisPoints;
            } else {
                points = (row.chassisPoints ?? 0) * (row.quantity ?? 1);
            }
            const power = (row.powerPoints ?? 0) * (row.quantity ?? 1);

            chassisSpent += points;
            // A system that is switched off draws nothing.
            if (!row.isOffline) powerConsumed += power;

            return {
                ...row,
                index,
                resolvedChassisPoints: points,
                resolvedPowerPoints: power,
                percentBreakdown: breakdown,
                unitByUnitPoints,
                // True when grouping actually changed the price — the whole reason
                // the minimum-factor rule exists.
                isDenominationRounded: unitByUnitPoints !== null && unitByUnitPoints !== points,
            };
        });

        // Limbs take 5% each and hand the same space back inside the limb.
        const limbPercent = ROBOT_LIMB_PERCENT * (this.limbCount ?? 0);
        const limbCost = AlternityMathService.decomposeChassisPercent(limbPercent, chassis.factors);
        this.limbChassisPoints = limbCost.chassisPoints;
        this.limbPercent = limbPercent;
        // Diminutive robots "cannot use limbs, they are too small".
        this.hasIllegalLimbs = !sizeInfo.canUseLimbs && (this.limbCount ?? 0) > 0;

        this.chassisSpent = chassisSpent;
        this.chassisFree  = this.chassisPoints - chassisSpent;
        this.isOverChassis = this.chassisFree < 0;

        // ── Budget 2: Power ──────────────────────────────────────────────────
        this.powerConsumed = Math.round(powerConsumed * 100) / 100;
        this.powerSurplus  = Math.round((this.powerGenerated - powerConsumed) * 100) / 100;
        // Not an error: an over-drawn robot shuts systems down to cope.
        this.isPowerDeficit = this.powerSurplus < 0;

        // ── Budget 3: Active memory ──────────────────────────────────────────
        const memory = AlternityMathService.calculateRobotMemoryLoad(
            processor?.mact ?? null,
            this.skills ?? [],
            { reservedSlots: this.reservedMemorySlots ?? 0, hasAI: this.hasInstalledAI }
        );
        this.memory = memory;

        // ── Budget 4: Skill points ───────────────────────────────────────────
        const perkFlawBalance = (this.perksFlaws ?? [])
            .reduce((sum, entry) => sum + (entry.skillPointChange ?? 0), 0);
        const spentSkillPoints = (this.skills ?? [])
            .reduce((sum, skill) => sum + (skill.skillPointCost ?? 0), 0);
        this.perkFlawBalance = perkFlawBalance;
        this.skillPoints = AlternityMathService.calculateRobotSkillPoints(
            int, perkFlawBalance, spentSkillPoints
        );

        // ── Derived stats ────────────────────────────────────────────────────
        this.actionCheck = AlternityMathService.calculateRobotActionCheck(int, dex, {
            profession: this.profession,
        });
        this.actionCheckModifier = processor?.actionCheckModifier ?? '+d0';

        const actions = AlternityMathService.calculateRobotActionsPerRound(int, dex, {
            processorMax: processor?.maxActionsPerRound ?? null,
            // Diminutive robots "do not require cabling"; nothing caps them there.
            cablingMax: sizeInfo.needsCabling ? (cabling?.maxActionsPerRound ?? null) : null,
        });
        this.actionsPerRound = actions.actionsPerRound;
        this.actionsCappedBy = actions.cappedBy;

        const durability = AlternityMathService.calculateRobotDurability(con, {
            hasFatigueTrack: this.hasFatigueTrack,
        });
        this.durability = {
            stun:    { value: this.damage?.stun ?? 0,    max: durability.stun },
            wound:   { value: this.damage?.wound ?? 0,   max: durability.wound },
            mortal:  { value: this.damage?.mortal ?? 0,  max: durability.mortal },
            fatigue: { value: this.damage?.fatigue ?? 0, max: durability.fatigue ?? 0 },
        };
        this.hasFatigue = durability.fatigue !== null;

        // Display-only aggregate so Foundry's token bars have a value/max pair.
        this.integrity = {
            value: Math.max(0, durability.mortal - (this.damage?.mortal ?? 0)),
            max:   durability.mortal,
        };

        // Size supplies flat resistance modifiers, movement and stealth shifts.
        this.movementModifier = sizeInfo.movement;
        this.dexResistanceModifier = sizeInfo.dexResistance;
        this.strResistanceModifier = sizeInfo.strResistance;
        this.stealthModifier = sizeInfo.stealth;

        // ── Hardware ceilings on the ability scores ──────────────────────────
        // The processor caps mental scores outright and the chassis caps physical
        // ones, so a robot can be built that simply cannot hold the numbers on it.
        this.abilityCaps = {
            STR: sizeInfo.maxStr,
            DEX: sizeInfo.maxDex,
            CON: sizeInfo.maxCon,
            INT: processor?.mint ?? null,
            WIL: processor?.mwil ?? null,
            PER: processor?.mper ?? null,
        };
        this.abilityBreaches = ROBOT_ABILITIES.filter((key) => {
            const cap = this.abilityCaps[key];
            return cap !== null && cap !== undefined && (abilities[key] ?? 0) > cap;
        });

        // "Mrnk: Maximum usable ranks in a skill" — ranks above it are dead weight.
        this.maxSkillRank = processor?.mrnk ?? null;
        this.overRankedSkills = (this.skills ?? [])
            .filter((s) => !s.isBroad && this.maxSkillRank !== null && (s.rank ?? 0) > this.maxSkillRank)
            .map((s) => s.name || 'Unnamed skill');

        // Robots have no Last Resort points at all — a Free Agent robot takes an
        // extra resistance-modifier increase instead. Exposed so the sheet can say
        // so rather than leaving a reader wondering where the track went.
        this.hasLastResort = false;

        // ── Status summary ───────────────────────────────────────────────────
        if (durability.mortal > 0 && (this.damage?.mortal ?? 0) >= durability.mortal) {
            this.status = 'Destroyed';
        } else if ((this.damage?.wound ?? 0) >= durability.wound) {
            this.status = 'Disabled';
        } else if ((this.damage?.stun ?? 0) >= durability.stun) {
            this.status = 'Shutdown';
        } else if (this.isPowerDeficit || memory.isOverloaded || this.isOverChassis) {
            this.status = 'Strained';
        } else {
            this.status = 'Operational';
        }
    }

    /** @override */
    static migrateData(source) {
        return super.migrateData(source);
    }
}
